"""GPU-resident BT.709 SDR -> graded BT.2020/PQ -> P010.

The grade is generated by the existing validated OpenCL implementation. CUDA
uses the same equations. This optional backend uses bilinear input chroma and
centred box-filtered output chroma with ordered dithering, not zimg's error
diffusion. CPU/host compilation of the same scalar code is for tests only.
"""
from gpu_colour import kernel_source
from creative_hdr import CreativeHDRSettings


COMMON = r'''
#ifdef __CUDACC__
#define FN __device__ __forceinline__
#else
#define FN inline
#include <math.h>
#include <cmath>
#endif
struct V { float x,y,z; };
FN V vec(float a,float b,float c) { return {a,b,c}; }
FN V vec(float a) { return {a,a,a}; }
FN V operator+(V a,V b) { return vec(a.x+b.x,a.y+b.y,a.z+b.z); }
FN V operator-(V a,V b) { return vec(a.x-b.x,a.y-b.y,a.z-b.z); }
FN V operator*(V a,V b) { return vec(a.x*b.x,a.y*b.y,a.z*b.z); }
FN V operator+(V a,float b) { return a+vec(b); }
FN V operator+(float a,V b) { return vec(a)+b; }
FN V operator-(V a,float b) { return a-vec(b); }
FN V operator*(V a,float b) { return vec(a.x*b,a.y*b,a.z*b); }
FN V operator*(float a,V b) { return b*a; }
FN V& operator*=(V& a,float b) { a=a*b; return a; }
FN V maxv(V a,float b) { return vec(fmaxf(a.x,b),fmaxf(a.y,b),fmaxf(a.z,b)); }
FN float maxv(float a,float b) { return fmaxf(a,b); }
FN float minv(float a,float b) { return fminf(a,b); }
FN float clipv(float a,float l,float h) { return fminf(h,fmaxf(a,l)); }
FN V clipv(V a,float l,float h) { return vec(clipv(a.x,l,h),clipv(a.y,l,h),clipv(a.z,l,h)); }
FN float luma(V a) { return .2627f*a.x+.678f*a.y+.0593f*a.z; }
// zimg's BT.709 display-referred linearisation uses BT.1886 (gamma 2.4).
FN V linear709(float y,float cb,float cr) {
 V r=vec(y+1.5748f*cr,y-.1873242729f*cb-.4681242729f*cr,y+1.8556f*cb);
 r=vec(powf(fmaxf(r.x,0.f),2.4f),powf(fmaxf(r.y,0.f),2.4f),powf(fmaxf(r.z,0.f),2.4f));
 return vec(.6274038959f*r.x+.3292830384f*r.y+.0433130657f*r.z,
            .0690972894f*r.x+.9195403951f*r.y+.0113623156f*r.z,
            .0163914389f*r.x+.0880133079f*r.y+.8955952532f*r.z);
}
FN float pq(float linear,float white) {
 float p=powf(clipv(linear*white/10000.f,0.f,1.f),.1593017578125f);
 return powf((.8359375f+18.8515625f*p)/(1.f+18.6875f*p),78.84375f);
}
FN V pq_yuv(V rgb,float white) {
 V p=vec(pq(rgb.x,white),pq(rgb.y,white),pq(rgb.z,white));
 float y=luma(p);
 return vec(y,(p.z-y)/1.8814f,(p.x-y)/1.4746f);
}
FN float dither(int x,int y) {
 // 4x4 Bayer, zero-mean, one quantisation-step peak-to-peak; no time flicker.
 const int b[16]={0,8,2,10,12,4,14,6,3,11,1,9,15,7,13,5};
 return (b[(y&3)*4+(x&3)]+.5f)/16.f-.5f;
}
FN unsigned short quantise(float v,int lo,int hi,float noise) {
 return (unsigned short)((int)floorf(clipv(v+noise,(float)lo,(float)hi)+.5f)<<6);
}
'''


def colour_source(grade=None, white_nits=200):
    """Generate shared scalar grade source (host-testable and CUDA-compilable)."""
    grade = grade or CreativeHDRSettings()
    grade.validate(white_nits)
    original = kernel_source(grade, white_nits)
    start = original.index('float3 grade_pixel(float3 rgb) {')
    body = original[start:original.index('\nfloat3 pixel(', start)]
    body = body.replace('float3 grade_pixel(float3 rgb)', 'FN V grade_pixel(V rgb)')
    body = body.replace('(float3)(', 'vec(').replace('pow(', 'powf(').replace('exp(', 'expf(')
    body = body.replace('fmax(', 'maxv(').replace('fmin(', 'minv(').replace('clamp(', 'clipv(')
    return COMMON + '\n' + body


KERNELS = r'''
FN int edge(int a,int end) { return a<0?0:(a>=end?end-1:a); }
template<typename T> FN float chroma(const T* uv,int pitch,int w,int h,float x,float y,int c,float scale) {
 int ix=(int)floorf(x), iy=(int)floorf(y); float a=x-ix,b=y-iy;
 int x0=edge(ix,w), x1=edge(ix+1,w), y0=edge(iy,h), y1=edge(iy+1,h);
 float top=uv[y0*pitch+2*x0+c]*(1.f-a)+uv[y0*pitch+2*x1+c]*a;
 float bot=uv[y1*pitch+2*x0+c]*(1.f-a)+uv[y1*pitch+2*x1+c]*a;
 return (top*(1.f-b)+bot*b)*scale;
}
template<typename T> FN void convert(const T* y,const T* uv,int yp,int up,int w,int h,
 int full,int centred,int bits,float white,int mode,float* result,float* light) {
 int x=blockIdx.x*blockDim.x+threadIdx.x, j=blockIdx.y*blockDim.y+threadIdx.y;
 if(x>=w||j>=h) return;
 float s=bits==10?1.f/64.f:1.f;
 float mult=bits==10?4.f:1.f, maximum=bits==10?1023.f:255.f;
 float yy=y[j*yp+x]*s;
 float cb=chroma(uv,up,w/2,h/2,x*.5f-(centred?.25f:0.f),j*.5f-.25f,0,s);
 float cr=chroma(uv,up,w/2,h/2,x*.5f-(centred?.25f:0.f),j*.5f-.25f,1,s);
 yy=full?yy/maximum:(yy-16.f*mult)/(219.f*mult);
 cb=(cb-128.f*mult)/(full?maximum:224.f*mult);
 cr=(cr-128.f*mult)/(full?maximum:224.f*mult);
 V rgb=grade_pixel(linear709(yy,cb,cr));
 int i=j*w+x,n=w*h;
 // Preserve non-finite values for the reduction/validation to reject them.
 light[i]=isfinite(rgb.x)&&isfinite(rgb.y)&&isfinite(rgb.z)?clipv(luma(rgb)*white,0.f,10000.f):nanf("");
 if(mode) {
   V out=mode==2?rgb:pq_yuv(rgb,white);
   result[i]=out.x; result[n+i]=out.y; result[2*n+i]=out.z;
 }
}
extern "C" __global__ void convert8(const unsigned char* y,const unsigned char* uv,int yp,int up,int w,int h,
 int full,int centred,int bits,float white,int mode,float* result,float* light) {
 convert(y,uv,yp,up,w,h,full,centred,bits,white,mode,result,light);
}
extern "C" __global__ void convert16(const unsigned short* y,const unsigned short* uv,int yp,int up,int w,int h,
 int full,int centred,int bits,float white,int mode,float* result,float* light) {
 convert(y,uv,yp,up,w,h,full,centred,bits,white,mode,result,light);
}
extern "C" __global__ void pack_p010(const float* a,unsigned short* out,int w,int h) {
 int x=2*(blockIdx.x*blockDim.x+threadIdx.x),y=2*(blockIdx.y*blockDim.y+threadIdx.y);
 if(x>=w||y>=h) return;
 int n=w*h; float u=0.f,v=0.f;
 for(int dy=0;dy<2;dy++) for(int dx=0;dx<2;dx++) {
  int i=(y+dy)*w+x+dx;
  out[i]=quantise(64.f+876.f*a[i],64,940,dither(x+dx,y+dy));
  u+=a[n+i]; v+=a[2*n+i];
 }
 int i=n+(y/2)*w+x;
 out[i]=quantise(512.f+224.f*u,64,960,dither(x/2,y/2));
 out[i+1]=quantise(512.f+224.f*v,64,960,dither(x/2+1,y/2));
}
'''


def cuda_source(grade=None, white_nits=200):
    return colour_source(grade, white_nits) + KERNELS
